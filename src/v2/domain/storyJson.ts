const ID_RE = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,47}$/;
const ASPECT_RE = /^\d+(\.\d+)?:\d+(\.\d+)?$/;
const MAX_ERRORS = 40;

/** Pull the JSON object out of what people paste: raw JSON, a ```json fence, or chat text around it. */
export function extractJson(text: string): string {
  const t = text.replace(/^\uFEFF/, "").trim();
  const fence = /```(?:json|JSON)?\s*\n([\s\S]*?)```/.exec(t);
  if (fence) return fence[1].trim();
  if (t.startsWith("{")) return t;
  const a = t.indexOf("{"), b = t.lastIndexOf("}");
  return a >= 0 && b > a ? t.slice(a, b + 1) : t;
}

/** "line 3, column 7" for a character offset. */
export function lineCol(text: string, pos: number): string {
  const before = text.slice(0, Math.max(0, pos));
  const line = before.split("\n").length;
  return `line ${line}, column ${pos - before.lastIndexOf("\n")}`;
}

/**
 * Locate the first JSON syntax error with a friendly hint. Browsers word (and position) JSON.parse
 * errors differently — Safari gives no offset at all — so we scan ourselves for consistent messages.
 */
export function jsonSyntaxError(text: string): { pos: number; message: string } | undefined {
  let i = 0;
  const ws = () => { while (i < text.length && /\s/.test(text[i])) i++; };
  const shown = () => (i >= text.length ? "the end of the text" : `"${text[i]}"`);
  class Fail { constructor(public pos: number, public message: string) {} }
  const fail = (message: string): never => { throw new Fail(i, message); };
  const value = (): void => {
    ws();
    const c = text[i];
    if (c === "{") {
      i++; ws();
      if (text[i] === "}") { i++; return; }
      for (;;) {
        ws();
        if (text[i] === "}") fail("remove the comma before }");
        if (text[i] === "'") fail("use double quotes \" for names, not '");
        if (text[i] !== '"') fail(`expected a "name" in quotes, found ${shown()}`);
        string(); ws();
        if (text[i] !== ":") fail(`expected : after the name, found ${shown()}`);
        i++; value(); ws();
        if (text[i] === ",") { i++; continue; }
        if (text[i] === "}") { i++; return; }
        fail(`expected , or } — found ${shown()} (a missing comma?)`);
      }
    }
    if (c === "[") {
      i++; ws();
      if (text[i] === "]") { i++; return; }
      for (;;) {
        ws();
        if (text[i] === "]") fail("remove the comma before ]");
        value(); ws();
        if (text[i] === ",") { i++; continue; }
        if (text[i] === "]") { i++; return; }
        fail(`expected , or ] — found ${shown()} (a missing comma?)`);
      }
    }
    if (c === '"') return string();
    if (c === "'") fail("use double quotes \" for text, not '");
    if (c === "/") fail("comments are not allowed in JSON");
    const lit = /^(-?\d+(\.\d+)?([eE][+-]?\d+)?|true|false|null)/.exec(text.slice(i));
    if (lit) { i += lit[0].length; return; }
    fail(`expected a value, found ${shown()}`);
  };
  const string = () => {
    i++;
    while (i < text.length && text[i] !== '"') {
      if (text[i] === "\n") fail("line break inside text — use \\n");
      i += text[i] === "\\" ? 2 : 1;
    }
    if (i >= text.length) fail("text is missing its closing \"");
    i++;
  };
  try {
    value(); ws();
    if (i < text.length) fail(`unexpected ${shown()} after the end of the JSON`);
  } catch (e) {
    if (e instanceof Fail) return { pos: e.pos, message: e.message };
    throw e;
  }
  return undefined;
}

export function parseStoryboard(text: string): StoryParseResult {
  const json = extractJson(text);
  if (!json) return { ok: false, errors: [{ path: "", message: "Nothing to import — paste the storyboard JSON or choose a .json file." }], warnings: [] };
  let raw: unknown;
  try { raw = JSON.parse(json); } catch {
    const at = jsonSyntaxError(json);
    const where = at ? ` at ${lineCol(json, at.pos)}: ${at.message}` : "";
    return { ok: false, errors: [{ path: "", message: `Not valid JSON${where}. Tip: ask the AI to reply with only the JSON in one code block.`, ...(at ? { at: at.pos } : {}) }], warnings: [] };
  }
  return validateStoryboard(raw);
}

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);
const str = (v: unknown) => (typeof v === "string" ? v.trim() : undefined);
const num = (v: unknown): number | undefined => (typeof v === "number" && Number.isFinite(v) ? v : undefined);
const HEX_RE = /^#([0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
/** Fields a storyboard text style may set (V2-SB-127): the same names as textStyle preset data and text clips. */
export const TEXT_STYLE_KEYS = ["font", "size", "color", "align", "bold", "italic", "letterSpacing", "lineHeight", "strokeWidth", "strokeColor", "shadow", "background", "effect", "effectColor"];
/** Numeric style extras: allowed range and unit (V2-SB-127). */
const STYLE_RANGES: Record<string, [number, number, string]> = {
  letterSpacing: [-0.2, 1, "extra space between letters, in em"],
  lineHeight: [0.8, 3, "line height multiplier"],
  strokeWidth: [0, 0.3, "outline width, as a fraction of the font size"],
};
/** Missing shadow / background fields are filled from these (also the text panel's defaults). */
export const TEXT_SHADOW_DEFAULT = { color: "#000000", blur: 0.15, x: 0.03, y: 0.03 };
export const TEXT_BACKGROUND_DEFAULT = { color: "#000000", opacity: 0.6 };
const KIND_LABEL: Record<PresetKind, string> = { textAnimIn: "in animation", textAnimOut: "out animation", textAnimLoop: "loop animation", effect: "text effect", videoEffect: "effect", transition: "transition", sticker: "sticker", textStyle: "text style", blend: "blend mode" };
const list = (xs: string[], max = 12) => `${xs.slice(0, max).join(", ")}${xs.length > max ? ", …" : ""}`;
const fmt = (n: number) => String(Math.round(n * 1000) / 1000);

/** Frame width ÷ height for an aspect string like "16:9" (fallback 16:9). */
export function aspectRatio(aspect: string): number {
  const m = /^(\d+(?:\.\d+)?):(\d+(?:\.\d+)?)$/.exec(aspect);
  const r = m ? Number(m[1]) / Number(m[2]) : NaN;
  return Number.isFinite(r) && r > 0 ? r : 16 / 9;
}

/** Line height used to fit a text size to a box: size = box height ÷ (lines × TEXT_LINE_HEIGHT). */
export const TEXT_LINE_HEIGHT = 1.2;
/** Default text size (fraction of frame height) when neither style, textStyle nor box gives one. */
export const DEFAULT_TEXT_SIZE = 0.1;

/**
 * Rough rendered width of `text` as a fraction of frame WIDTH (no wrapping; the longest line counts). Used only for the
 * "may overflow" warning, so it errs on the generous side of a real browser measurement.
 */
export function estimateTextWidth(text: string, opts: { font?: string; size: number; bold?: boolean; aspect: string }): number {
  const f = getFont(opts.font) ?? FONTS[0];
  const mono = f.id === "mono";
  const em = (line: string) => [...line].reduce((t, c) => t + (mono ? 1 : c === " " ? 0.55 : /[A-Z0-9]/.test(c) ? 1.3 : /[il.,:;'!|]/.test(c) ? 0.55 : /[mwMW]/.test(c) ? 1.5 : 1) * f.width, 0);
  const widest = Math.max(0, ...text.split("\n").map(em));
  return (widest * opts.size * (opts.bold ? 1.06 : 1)) / aspectRatio(opts.aspect);
}

export function validateStoryboard(raw: unknown): StoryParseResult {
  const errors: StoryIssue[] = [], warnings: StoryIssue[] = [];
  const err = (path: string, message: string) => { if (errors.length < MAX_ERRORS) errors.push({ path, message }); };
  const warn = (path: string, message: string) => warnings.push({ path, message });
  if (!isObj(raw)) return { ok: false, errors: [{ path: "", message: "The storyboard must be a JSON object { … }." }], warnings };

  if (raw.format === undefined) warn("format", `Missing "format"; assuming "${STORYBOARD_FORMAT}".`);
  else if (raw.format !== STORYBOARD_FORMAT) err("format", `Unsupported format "${String(raw.format)}" — expected "${STORYBOARD_FORMAT}".`);

  const m = isObj(raw.meta) ? raw.meta : (err("meta", 'Missing "meta" object with at least "title".'), {} as Obj);
  const title = str(m.title);
  if (isObj(raw.meta) && !title) err("meta.title", "Story title is required.");
  let aspect = str(m.aspect) ?? "";
  if (!aspect) { aspect = "16:9"; if (isObj(raw.meta)) warn("meta.aspect", 'No aspect given; using "16:9".'); }
  else if (!ASPECT_RE.test(aspect)) { err("meta.aspect", `Aspect "${aspect}" should look like "16:9" or "9:16".`); }
  const meta: StoryMeta = { title: title ?? "", aspect };
  for (const k of ["logline", "synopsis", "style", "language"] as const) { const v = str(m[k]); if (v) meta[k] = v; }

  const strList = (v: unknown, path: string): string[] => {
    if (v === undefined) return [];
    if (!Array.isArray(v)) { err(path, "Should be a list of strings."); return []; }
    return v.flatMap((x, i) => { const s = str(x); if (!s) { err(`${path}[${i}]`, "Should be a non-empty string."); return []; } return [s]; });
  };
  const checkId = (v: unknown, path: string, seen: Set<string>, what: string): string => {
    const id = str(v) ?? "";
    if (!id) err(`${path}.id`, `Each ${what} needs an "id".`);
    else if (!ID_RE.test(id)) err(`${path}.id`, `Id "${id}" may only use letters, digits, "_", "-", "." (max 48).`);
    else if (seen.has(id)) err(`${path}.id`, `Duplicate ${what} id "${id}".`);
    seen.add(id);
    return id;
  };

  /** A text look (meta.textStyles entry or a layer's inline style). Bad values warn and are dropped; unknown fields warn and pass through. */
  const textStyleOf = (v: unknown, path: string): StoryTextStyle | undefined => {
    if (v === undefined) return undefined;
    if (!isObj(v)) { err(path, 'Should be an object like { "font": "serif", "size": 0.08, "color": "#ffffff", "align": "center", "bold": true }.'); return undefined; }
    const out: StoryTextStyle = { ...v };
    if (v.font !== undefined) {
      const f = str(v.font);
      if (f) out.font = f; else delete out.font;
      if (!f || !getFont(f)) warn(`${path}.font`, `Unknown font ${JSON.stringify(v.font)}; using "sans". Fonts: ${FONTS.map((x) => x.id).join(", ")}.`);
    }
    if (v.size !== undefined) {
      const n = num(v.size);
      if (n === undefined || n <= 0 || n > 1) { delete out.size; warn(`${path}.size`, `Size ${JSON.stringify(v.size)} is ignored: it is a fraction of the frame height, e.g. 0.08.`); }
    }
    if (v.color !== undefined && !(typeof v.color === "string" && HEX_RE.test(v.color))) { delete out.color; warn(`${path}.color`, `Color ${JSON.stringify(v.color)} is ignored: use a hex value like "#ffffff".`); }
    if (v.align !== undefined && !TEXT_ALIGNS.includes(v.align as never)) { delete out.align; warn(`${path}.align`, `Align ${JSON.stringify(v.align)} is ignored: use "left", "center" or "right".`); }
    if (v.bold !== undefined && typeof v.bold !== "boolean") {
      const n = num(v.bold) ?? (v.bold === "bold" ? 700 : v.bold === "normal" ? 400 : undefined);
      if (n === undefined) { delete out.bold; warn(`${path}.bold`, `Bold ${JSON.stringify(v.bold)} is ignored: use true or false.`); }
      else out.bold = n >= 600;
    }
    // V2-SB-127: style extras (the same fields as textStyle preset data). Bad values warn and are dropped.
    if (v.italic !== undefined && typeof v.italic !== "boolean") { delete out.italic; warn(`${path}.italic`, `Italic ${JSON.stringify(v.italic)} is ignored: use true or false.`); }
    for (const [k, [lo, hi, unit]] of Object.entries(STYLE_RANGES)) {
      if (v[k] === undefined) continue;
      const n = num(v[k]);
      if (n === undefined || n < lo || n > hi) { delete out[k]; warn(`${path}.${k}`, `${k} ${JSON.stringify(v[k])} is ignored: use ${lo} to ${hi} (${unit}).`); }
    }
    for (const k of ["strokeColor", "effectColor"]) if (v[k] !== undefined && !(typeof v[k] === "string" && HEX_RE.test(v[k] as string))) { delete out[k]; warn(`${path}.${k}`, `${k} ${JSON.stringify(v[k])} is ignored: use a hex value like "#000000".`); }
    if (v.shadow !== undefined && v.shadow !== null) {
      const sh = v.shadow, d = TEXT_SHADOW_DEFAULT;
      const ok = isObj(sh) && (sh.color === undefined || (typeof sh.color === "string" && HEX_RE.test(sh.color))) && (["blur", "x", "y"] as const).every((k) => sh[k] === undefined || (num(sh[k]) !== undefined && Math.abs(num(sh[k])!) <= 1 && (k !== "blur" || num(sh[k])! >= 0)));
      if (!ok) { delete out.shadow; warn(`${path}.shadow`, `shadow is ignored: use { "color": "#000000", "blur": 0-1, "x": -1-1, "y": -1-1 } (blur and offsets are fractions of the font size), or null for none.`); }
      else out.shadow = { color: (sh.color as string | undefined) ?? d.color, blur: num(sh.blur) ?? d.blur, x: num(sh.x) ?? d.x, y: num(sh.y) ?? d.y };
    }
    if (v.background !== undefined && v.background !== null) {
      const bg = v.background, d = TEXT_BACKGROUND_DEFAULT;
      const ok = isObj(bg) && (bg.color === undefined || (typeof bg.color === "string" && HEX_RE.test(bg.color))) && (bg.opacity === undefined || (num(bg.opacity) !== undefined && num(bg.opacity)! >= 0 && num(bg.opacity)! <= 1));
      if (!ok) { delete out.background; warn(`${path}.background`, `background is ignored: use { "color": "#000000", "opacity": 0-1 }, or null for none.`); }
      else out.background = { color: (bg.color as string | undefined) ?? d.color, opacity: num(bg.opacity) ?? d.opacity };
    }
    if (v.effect !== undefined && v.effect !== "none") {
      const ref = str(v.effect) ? parsePresetRef(str(v.effect)!) : undefined;
      if (!ref || !getPreset("effect", ref.id)) { delete out.effect; warn(`${path}.effect`, `Unknown text effect ${JSON.stringify(v.effect)}; ignoring it. Text effects: ${list(["none", ...listPresets("effect").map((d) => d.id)])}.`); }
      else out.effect = ref.id;
    }
    for (const k of Object.keys(v)) if (!TEXT_STYLE_KEYS.includes(k)) warn(`${path}.${k}`, `Unknown text style field "${k}" has no effect (kept for re-export). Fields: ${TEXT_STYLE_KEYS.join(", ")}.`);
    return out;
  };

  // meta.textStyles: local looks; a clash with a registry textStyle id is allowed (local wins) but warned.
  const localStyles: Record<string, StoryTextStyle> = {};
  if (m.textStyles !== undefined) {
    if (!isObj(m.textStyles)) err("meta.textStyles", 'Should be an object: { "<style id>": { "font": …, "size": …, "color": … } }.');
    else for (const [id, v] of Object.entries(m.textStyles)) {
      const path = `meta.textStyles.${id}`;
      if (!ID_RE.test(id)) { err(path, `Style id "${id}" may only use letters, digits, "_", "-", "." (max 48).`); continue; }
      if (getPreset("textStyle", id)) warn(path, `"${id}" is also a built-in text style; this storyboard's own style is used.`);
      const st = textStyleOf(v, path);
      if (st) localStyles[id] = st;
    }
    if (Object.keys(localStyles).length) meta.textStyles = localStyles;
  }

  /**
   * A preset reference. Unknown ids (or ones that are not a valid `id` / `id@N`) warn and fall back; a version pin that
   * differs from the registry warns and uses the current version. The id is always kept as written for re-export.
   */
  const presetRef = (kind: PresetKind, v: unknown, path: string, fallback: string): string | undefined => {
    if (v === undefined) return undefined;
    const ref = str(v);
    if (!ref) { warn(path, `Should be a ${KIND_LABEL[kind]} id; using ${fallback}.`); return undefined; }
    const r = parsePresetRef(ref);
    if (kind === "textStyle" && r && localStyles[r.id]) return ref;
    const d = r ? getPreset(kind, r.id) : undefined;
    if (!d) warn(path, `Unknown ${KIND_LABEL[kind]} "${ref}"; using ${fallback} (the id is kept for export). Known: ${list([...(kind === "textStyle" ? Object.keys(localStyles) : []), ...listPresets(kind).map((x) => x.id)], 20)}.`);
    else if (r?.version !== undefined && r.version !== d.version) warn(path, `"${ref}" asks for version ${r.version}, but "${r.id}" is version ${d.version} now; using the current version.`);
    return ref;
  };
  /** Preset params: keys from the descriptor's ParamSpec (plus `extra` keys). Unknown keys and out-of-range numbers warn. */
  const paramsOf = (v: unknown, path: string, d: PresetDescriptor | undefined, extra: string[] = []): StoryParams | undefined => {
    if (v === undefined) return undefined;
    if (!isObj(v)) { warn(path, "Params should be an object of numbers or strings; ignoring them."); return undefined; }
    const out: StoryParams = {};
    for (const [k, x] of Object.entries(v)) {
      if (typeof x !== "number" && typeof x !== "string") { warn(`${path}.${k}`, `Param "${k}" should be a number or a string; ignoring it.`); continue; }
      out[k] = x;
      if (!d || extra.includes(k)) continue;
      const spec = d.params.find((p) => p.key === k);
      if (!spec) warn(`${path}.${k}`, `"${d.id}" has no param "${k}"; it is ignored.${d.params.length ? ` Params: ${d.params.map((p) => p.key).join(", ")}.` : ""}`);
      else if (spec.type === "number" && (typeof x !== "number" || x < spec.min || x > spec.max)) warn(`${path}.${k}`, typeof x !== "number" ? `Param "${k}" should be a number; using the default ${spec.default}.` : `Param "${k}" = ${x} is outside ${spec.min}–${spec.max}; it will be clamped.`);
    }
    return out;
  };
  const descriptorOf = (kind: PresetKind, ref: string | undefined) => { const r = ref ? parsePresetRef(ref) : undefined; return r ? getPreset(kind, r.id) : undefined; };
  /** startSec/endSec relative to the shot: 0 <= start < end <= duration. Missing values are errors only when `required`. */
  const timeRange = (o: Obj, path: string, dur: number, required: boolean): { startSec?: number; endSec?: number } => {
    const out: { startSec?: number; endSec?: number } = {};
    const s = o.startSec, e = o.endSec;
    if (s !== undefined || required) {
      const v = num(s);
      if (v === undefined) err(`${path}.startSec`, s === undefined ? 'Needs "startSec" (seconds from the start of the shot).' : `startSec ${JSON.stringify(s)} must be a number of seconds.`);
      else if (v < 0) err(`${path}.startSec`, `startSec ${fmt(v)} can't be negative.`);
      else out.startSec = v;
    }
    if (e !== undefined || required) {
      const v = num(e);
      if (v === undefined) err(`${path}.endSec`, e === undefined ? 'Needs "endSec" (seconds from the start of the shot).' : `endSec ${JSON.stringify(e)} must be a number of seconds.`);
      else out.endSec = v;
    }
    const start = out.startSec ?? 0, end = out.endSec ?? dur;
    if (Number.isFinite(end) && end <= start) err(`${path}.endSec`, `endSec ${fmt(end)} must be after startSec ${fmt(start)}.`);
    else if (out.endSec !== undefined && Number.isFinite(dur) && out.endSec > dur + 1e-9) err(`${path}.endSec`, `endSec ${fmt(out.endSec)} is past the end of the shot (durationSec ${fmt(dur)}).`);
    else if (out.startSec !== undefined && out.endSec === undefined && Number.isFinite(dur) && out.startSec >= dur) err(`${path}.startSec`, `startSec ${fmt(out.startSec)} is not inside the shot (durationSec ${fmt(dur)}).`);
    return out;
  };
  const pointOf = (v: unknown, path: string): StoryPoint | undefined => {
    if (!isObj(v) || num(v.x) === undefined || num(v.y) === undefined) { err(path, 'Should be { "x": 0.5, "y": 0.5 }: the text centre as fractions of the frame.'); return undefined; }
    const pt = { x: v.x as number, y: v.y as number };
    if (pt.x < 0 || pt.x > 1 || pt.y < 0 || pt.y > 1) warn(path, "The text centre is outside the frame (x and y are 0–1 fractions).");
    return pt;
  };
  const boxOf = (v: unknown, path: string): StoryBox | undefined => {
    const ok = isObj(v) && [v.x, v.y, v.width, v.height].every((x) => num(x) !== undefined);
    if (!ok) { err(path, 'Should be { "x", "y", "width", "height" }: top-left corner and size as fractions of the frame.'); return undefined; }
    const b = { x: v.x as number, y: v.y as number, width: v.width as number, height: v.height as number };
    if (b.width <= 0 || b.height <= 0) { err(path, "Box width and height must be greater than 0."); return undefined; }
    if (b.x < -1e-9 || b.y < -1e-9 || b.x + b.width > 1.001 || b.y + b.height > 1.001) warn(path, "The box reaches outside the frame (fractions 0–1 from the top-left).");
    return b;
  };

  // Shots first so asset sources can be checked against them.
  const rawShots = Array.isArray(raw.shots) ? raw.shots : (err("shots", 'Missing "shots" list.'), []);
  if (Array.isArray(raw.shots) && rawShots.length === 0) err("shots", "Add at least one shot.");
  const shotIds = new Set<string>();
  const shotPre = rawShots.map((s, i) => { const path = `shots[${i}]`; if (!isObj(s)) { err(path, "Each shot must be an object."); return undefined; } return { s, path, id: checkId(s.id, path, shotIds, "shot") }; });

  /**
   * assets[].references (V2-SB-123): asset ids, or objects { asset, role?, note? } that say how the image model should
   * use each attached image. An asset image has no end frame; "start-frame" means the base image to edit.
   */
  const assetRefsOf = (v: unknown, path: string) => {
    const ids: string[] = [], refs: StoryAssetRef[] = [];
    if (v === undefined) return refs;
    if (!Array.isArray(v)) { err(path, '"references" must be a list of asset ids or { "asset": "<asset id>", "role": "<role>" } objects.'); return refs; }
    v.forEach((r, j) => {
      const rp = `${path}[${j}]`;
      const asset = typeof r === "string" ? r.trim() : isObj(r) ? str(r.asset) ?? "" : "";
      if (!asset) return err(rp, typeof r === "string" || isObj(r) ? 'A reference needs the id of the asset to attach ("asset").' : 'Each reference must be an asset id or { "asset": "<asset id>", "role": "<role>", "note"?: "…" }.');
      if (ids.includes(asset)) return warn(rp, `Asset "${asset}" is already in this asset's references; the repeat is ignored.`);
      ids.push(asset);
      if (!isObj(r)) return void refs.push(asset);
      const note = str(r.note);
      let role: ReferenceRole | undefined;
      if (r.role !== undefined) {
        const w = str(r.role) as ReferenceRole;
        if (w === "end-frame") { warn(`${rp}.role`, 'An asset image has no end frame; using "detail". Use "start-frame" for the base image to edit.'); role = "detail"; }
        else if (REFERENCE_ROLES.includes(w)) role = w;
        else { warn(`${rp}.role`, `Unknown role ${JSON.stringify(r.role)}; using "detail". Roles: ${ASSET_REFERENCE_ROLES.join(", ")}.`); role = "detail"; }
      }
      refs.push({ asset, ...(role ? { role } : {}), ...(note ? { note } : {}) });
    });
    if (refs.filter((x) => typeof x !== "string" && x.role === "start-frame").length > 1) err(path, 'Only one reference can be "start-frame" (the base image to edit).');
    return refs;
  };

  const rawAssets = raw.assets === undefined ? [] : Array.isArray(raw.assets) ? raw.assets : (err("assets", '"assets" must be a list.'), []);
  const assetIds = new Set<string>();
  const assets: StoryAsset[] = [];
  rawAssets.forEach((a, i) => {
    const path = `assets[${i}]`;
    if (!isObj(a)) return err(path, "Each asset must be an object.");
    const id = checkId(a.id, path, assetIds, "asset");
    const type = str(a.type) as StoryAssetType;
    if (!STORY_ASSET_TYPES.includes(type)) err(`${path}.type`, `Type "${String(a.type ?? "")}" must be one of: ${STORY_ASSET_TYPES.join(", ")}.`);
    let source: StoryAssetSource = { type: "generate" };
    const src = a.source;
    if (src === undefined || src === "generate" || (isObj(src) && src.type === "generate")) source = { type: "generate" };
    else if (src === "upload" || (isObj(src) && src.type === "upload")) source = { type: "upload" };
    else if (isObj(src) && src.type === "lastFrame") {
      const shot = str(src.shot) ?? "";
      if (!shotIds.has(shot)) err(`${path}.source.shot`, shot ? `Unknown shot "${shot}" (shots: ${[...shotIds].join(", ")}).` : 'A lastFrame source needs "shot": the id of the shot whose last frame this is.');
      if (type === "html") err(`${path}.source`, 'An html asset can\'t be a last frame; use "generate" (the user asks their AI for the .html) or "upload".');
      if (type === "audio") err(`${path}.source`, 'An audio asset can\'t be a last frame; use "generate" (the user makes it with their AI voice or music tool) or "upload".');
      source = { type: "lastFrame", shot };
    } else err(`${path}.source`, 'Source must be "generate", "upload", or { "type": "lastFrame", "shot": "<shot id>" }.');
    const prompt = str(a.prompt) ?? "";
    if (source.type === "generate" && !prompt) err(`${path}.prompt`, type === "html" ? `Asset "${id}" is html, so its "prompt" must be a design brief for the user's AI (what it shows and how it moves).` : `Asset "${id}" is generated, so it needs a generation "prompt".`);
    const asp = str(a.aspect);
    if (asp && !ASPECT_RE.test(asp)) err(`${path}.aspect`, `Aspect "${asp}" should look like "16:9".`);
    const name = str(a.name) || id;
    const notes = str(a.notes);
    let params: Record<string, HtmlClipParam> | undefined;
    if (a.params !== undefined) {
      if (type !== "html") warn(`${path}.params`, `Only html assets expose "params"; it is ignored for this ${type || "unknown"} asset.`);
      else {
        for (const i of validateParamDecls(a.params)) err(`${path}.params`, i.message);
        const clean = cleanParamDecls(a.params);
        if (Object.keys(clean).length) params = clean;
      }
    }
    assets.push({ id, name, type, aspect: asp || aspect, prompt, references: assetRefsOf(a.references, `${path}.references`), source, qa: strList(a.qa, `${path}.qa`), ...(notes ? { notes } : {}), ...(params ? { params } : {}) });
  });
  assets.forEach((a, i) => a.references.map(assetRefId).forEach((r, j) => {
    if (r === a.id) err(`assets[${i}].references[${j}]`, `Asset "${a.id}" can't reference itself.`);
    else if (!assetIds.has(r)) err(`assets[${i}].references[${j}]`, `Unknown asset "${r}".`);
  }));
  const refCycle = findCycle(new Map(assets.map((a) => [a.id, a.references.map(assetRefId)])));
  if (refCycle) err("assets", `Assets reference each other in a loop: ${refCycle.join(" → ")}.`);
  const assetById = new Map(assets.map((a) => [a.id, a]));
  const unknownAsset = (id: string) => `Unknown asset "${id}"${assetIds.size ? ` (assets: ${list([...assetIds], 8)})` : ""}.`;

  /**
   * V2-HTML-PARAMS: per-use values for html asset `assetId`. Checked against the asset's declared `params` when it
   * declares any (unknown keys dropped with a warning, wrong types are errors, numbers clamped); otherwise any
   * number/string/boolean is kept and the clip's own manifest decides at render time.
   */
  const htmlParamsOf = (v: unknown, path: string, assetId: string | undefined): HtmlParamValues | undefined => {
    if (v === undefined) return undefined;
    if (!isObj(v)) { err(path, '"params" must be an object of values: { "<param>": value }.'); return undefined; }
    const decls = assetId ? assetById.get(assetId)?.params : undefined;
    const out: HtmlParamValues = {};
    for (const [k, val] of Object.entries(v)) {
      const kp = `${path}.${k}`;
      if (typeof val !== "number" && typeof val !== "string" && typeof val !== "boolean") { err(kp, `Param "${k}" must be a number, string or true/false.`); continue; }
      if (!decls) { out[k] = val; continue; }
      const spec = decls[k];
      if (!spec) { warn(kp, `Asset "${assetId}" declares no param "${k}" (params: ${Object.keys(decls).join(", ")}); it is ignored.`); continue; }
      const c = checkParamValue(spec, val);
      if (c.value === undefined) { err(kp, `Param "${k}" (${spec.type}) ${c.problem}.`); continue; }
      if (c.clamped) warn(kp, `Param "${k}": ${c.problem}.`);
      out[k] = c.value;
    }
    return Object.keys(out).length ? out : undefined;
  };

  const layersOf = (v: unknown, path: string, dur: number): StoryLayer[] | undefined => {
    if (v === undefined) return undefined;
    if (!Array.isArray(v)) { err(path, '"layers" must be a list.'); return undefined; }
    const ids = new Set<string>();
    const out: StoryLayer[] = [];
    v.forEach((l, j) => {
      const lp = `${path}[${j}]`;
      if (!isObj(l)) return err(lp, "Each layer must be an object.");
      const id = checkId(l.id, lp, ids, "layer");
      const type = str(l.type) as StoryLayerType;
      if (!LAYER_TYPES.includes(type)) return err(`${lp}.type`, `Layer type ${JSON.stringify(l.type ?? "")} must be one of: ${LAYER_TYPES.join(", ")}.`);
      if (l.trackMotion !== undefined) warn(`${lp}.trackMotion`, '"trackMotion" is not supported yet; it is ignored.');
      const blend = presetRef("blend", l.blend, `${lp}.blend`, '"normal"');
      let opacity: number | undefined;
      if (l.opacity !== undefined) {
        const o = num(l.opacity);
        if (o === undefined || o < 0 || o > 1) warn(`${lp}.opacity`, `opacity ${JSON.stringify(l.opacity)} is ignored: use 0 (invisible) to 1 (solid, the default).`);
        else opacity = o;
      }
      const look = { ...(blend ? { blend } : {}), ...(opacity !== undefined ? { opacity } : {}) };
      const range = timeRange(l, lp, dur, true);
      const startSec = range.startSec ?? 0, endSec = range.endSec ?? startSec;
      let follow: "shot" | undefined;
      if (l.follow !== undefined && l.follow !== "frame") {
        if (l.follow === "shot") follow = "shot";
        else warn(`${lp}.follow`, `follow ${JSON.stringify(l.follow)} is ignored: use "frame" (stays put, the default) or "shot" (moves with the shot's zoom and pan).`);
      }
      if (type === "text") {
        if (l.params !== undefined) warn(`${lp}.params`, 'Text layers have no "params"; it is ignored. For a reusable styled title, use an html layer with an html asset that exposes params.');
        const text = typeof l.text === "string" ? l.text : "";
        if (!text.trim()) err(`${lp}.text`, 'A text layer needs "text".');
        let position: StoryPoint | undefined, box: StoryBox | undefined;
        if (l.position !== undefined && l.box !== undefined) err(lp, 'Give either "position" (text centre) or "box" (text area), not both.');
        else if (l.position === undefined && l.box === undefined) err(lp, 'A text layer needs "position" { x, y } (preferred) or "box" { x, y, width, height }.');
        else if (l.position !== undefined) position = pointOf(l.position, `${lp}.position`);
        else box = boxOf(l.box, `${lp}.box`);
        const textStyle = presetRef("textStyle", l.textStyle, `${lp}.textStyle`, '"plain"');
        const style = textStyleOf(l.style, `${lp}.style`);
        let anim: StoryTextAnim | undefined;
        if (l.anim !== undefined) {
          if (!isObj(l.anim)) warn(`${lp}.anim`, 'Should be { "in"?, "out"?, "loop"?, "durationSec"? }; ignoring it.');
          else {
            anim = {};
            const kinds = { in: "textAnimIn", out: "textAnimOut", loop: "textAnimLoop" } as const;
            for (const k of ["in", "out", "loop"] as const) { const r = presetRef(kinds[k], l.anim[k], `${lp}.anim.${k}`, "no animation"); if (r) anim[k] = r; }
            if (l.anim.durationSec !== undefined) {
              const d = num(l.anim.durationSec);
              if (d === undefined || d <= 0) warn(`${lp}.anim.durationSec`, `durationSec ${JSON.stringify(l.anim.durationSec)} is ignored: use seconds greater than 0 (default 0.5).`);
              else { anim.durationSec = d; if (d * 2 > endSec - startSec + 1e-9) warn(`${lp}.anim.durationSec`, `In + out (${fmt(d * 2)} s) is longer than the layer (${fmt(endSec - startSec)} s); each will be shortened to half the layer.`); }
            }
          }
        }
        // Overflow hint: no wrapping, so a long line in a narrow box (or wider than the frame) is likely cut off.
        if (text.trim() && (position || box)) {
          const ref = textStyle ? parsePresetRef(textStyle) : undefined;
          const base: Obj = (ref && (localStyles[ref.id] ?? getPreset("textStyle", ref.id)?.data)) || {};
          const lines = Math.max(1, text.split("\n").length);
          const size = style?.size ?? (box ? box.height / (lines * TEXT_LINE_HEIGHT) : num(base.size) ?? DEFAULT_TEXT_SIZE);
          const font = getFont(style?.font) ? style!.font : getFont(str(base.font)) ? str(base.font) : undefined;
          const bold = style?.bold ?? (typeof base.bold === "boolean" ? base.bold : true);
          const w = estimateTextWidth(text, { font, size, bold, aspect });
          const room = box ? box.width : 1;
          if (w > room * 1.02) warn(`${lp}.text`, box ? `The text is about ${fmt(w)} of the frame wide but the box is ${fmt(box.width)}; it may overflow (text does not wrap). Use a smaller "style.size", a wider box or shorter text.` : `The text is about ${fmt(w)} of the frame wide and may run off screen (text does not wrap). Use a smaller "style.size" or shorter text.`);
        }
        out.push({ id, type, text, startSec, endSec, ...(position ? { position } : {}), ...(box ? { box } : {}), ...(textStyle ? { textStyle } : {}), ...(style ? { style } : {}), ...(anim ? { anim } : {}), ...(follow ? { follow } : {}), ...look });
      } else {
        const asset = str(l.asset) ?? "";
        const a = assetById.get(asset);
        if (!asset) err(`${lp}.asset`, `A ${type} layer needs "asset": the id of ${type === "html" ? "an html" : type === "image" ? "an image" : "a video"} asset.`);
        else if (!a) err(`${lp}.asset`, unknownAsset(asset));
        else if (type === "html" ? a.type !== "html" : type === "video" ? a.type !== "video" : !STILL_ASSET_TYPES.includes(a.type)) err(`${lp}.asset`, `A ${type} layer can't show asset "${asset}" (type ${a.type}); it needs ${type === "html" ? "an html" : type === "video" ? "a video" : "an image"} asset.`);
        if (l.position !== undefined) err(`${lp}.position`, `${type} layers are placed with "box" { x, y, width, height }, not "position".`);
        const box = l.box === undefined ? (l.position === undefined ? (err(`${lp}.box`, `A ${type} layer needs "box" { x, y, width, height }.`), undefined) : undefined) : boxOf(l.box, `${lp}.box`);
        let params: HtmlParamValues | undefined;
        if (l.params !== undefined) {
          if (type !== "html") warn(`${lp}.params`, `Only html layers take "params"; it is ignored for this ${type} layer.`);
          else params = htmlParamsOf(l.params, `${lp}.params`, a?.type === "html" ? asset : undefined);
        }
        if (box) out.push({ id, type, asset, startSec, endSec, box, ...(follow ? { follow } : {}), ...look, ...(params ? { params } : {}) });
      }
    });
    return out;
  };

  const effectsOf = (v: unknown, path: string, dur: number): StoryEffect[] | undefined => {
    if (v === undefined) return undefined;
    if (!Array.isArray(v)) { err(path, '"effects" must be a list.'); return undefined; }
    return v.flatMap((e, j) => {
      const ep = `${path}[${j}]`;
      if (!isObj(e)) { err(ep, "Each effect must be an object."); return []; }
      if (str(e.preset) === undefined || !str(e.preset)) { err(`${ep}.preset`, `An effect needs "preset": one of ${list(listPresets("videoEffect").map((d) => d.id))}.`); return []; }
      const preset = presetRef("videoEffect", e.preset, `${ep}.preset`, "no effect")!;
      const params = paramsOf(e.params, `${ep}.params`, descriptorOf("videoEffect", preset));
      return [{ preset, ...(params ? { params } : {}), ...timeRange(e, ep, dur, false) }];
    });
  };

  /**
   * shots[].references (V2-SB-120): known asset ids, at most one start-frame and one end-frame, no repeats. An unknown
   * role warns and is used as "detail"; a missing role is inferred from the asset type. Referenced assets missing
   * from the shot's "assets" are added to it, so they count as its inputs.
   */
  const referencesOf = (v: unknown, path: string, used: string[]): StoryReference[] | undefined => {
    if (v === undefined) return undefined;
    if (!Array.isArray(v)) { err(path, '"references" must be a list like [ { "asset": "<asset id>", "role": "start-frame" } ].'); return undefined; }
    const out: StoryReference[] = [];
    v.forEach((r, j) => {
      const rp = `${path}[${j}]`;
      if (!isObj(r)) return err(rp, 'Each reference must be an object { "asset": "<asset id>", "role": "<role>", "note"?: "…" }.');
      const asset = str(r.asset) ?? "";
      if (!asset) return err(`${rp}.asset`, 'A reference needs "asset": the id of the asset to attach.');
      const a = assetById.get(asset);
      if (!a) return err(`${rp}.asset`, unknownAsset(asset));
      if (out.some((x) => x.asset === asset)) return warn(rp, `Asset "${asset}" is already in this shot's references; the repeat is ignored.`);
      let role: ReferenceRole;
      if (r.role === undefined) role = inferReferenceRole(a.type, a.source.type === "lastFrame");
      else if (REFERENCE_ROLES.includes(str(r.role) as ReferenceRole)) role = str(r.role) as ReferenceRole;
      else { warn(`${rp}.role`, `Unknown role ${JSON.stringify(r.role)}; using "detail". Roles: ${REFERENCE_ROLES.join(", ")}.`); role = "detail"; }
      const note = str(r.note);
      out.push({ asset, role, ...(note ? { note } : {}) });
      if (!used.includes(asset)) used.push(asset);
    });
    for (const role of ["start-frame", "end-frame"] as const) {
      const n = out.filter((x) => x.role === role).length;
      if (n > 1) err(path, `A shot can have only one "${role}" reference, but it has ${n}.`);
    }
    return out;
  };

  /**
   * shots[].keyframe (V2-SB-124): { prompt, references?, qa? } for render "ai" shots. Its references are checked like an
   * asset's; its id `<shot id>.keyframe` must be free.
   */
  const keyframeOf = (v: unknown, path: string, shotId: string, mode: ShotRender): StoryKeyframe | undefined => {
    if (v === undefined) return undefined;
    if (!isObj(v)) { err(path, 'Should be { "prompt": "<the opening still>", "references"?: [ … ], "qa"?: [ … ] }.'); return undefined; }
    if (mode !== "ai") { warn(path, `A keyframe only applies to AI-generated clips; it is ignored for this render "${mode}" shot.`); return undefined; }
    const prompt = str(v.prompt) ?? "";
    if (!prompt) err(`${path}.prompt`, `Shot "${shotId}" has a keyframe, so it needs a keyframe "prompt" (the still image to generate first).`);
    if (assetIds.has(keyframeId(shotId))) err(path, `Asset id "${keyframeId(shotId)}" is reserved for the keyframe of shot "${shotId}"; rename that asset.`);
    const references = assetRefsOf(v.references, `${path}.references`);
    references.map(assetRefId).forEach((r, j) => { if (!assetIds.has(r)) err(`${path}.references[${j}]`, unknownAsset(r)); });
    return { prompt, references, qa: strList(v.qa, `${path}.qa`) };
  };

  const shots: StoryShot[] = [];
  for (const pre of shotPre) {
    if (!pre) continue;
    const { s, path, id } = pre;
    const dur = typeof s.durationSec === "number" ? s.durationSec : NaN;
    if (!(dur >= 0.5 && dur <= 120)) err(`${path}.durationSec`, s.durationSec === undefined ? `Shot "${id}" needs "durationSec" (seconds, 0.5–120).` : `Duration ${JSON.stringify(s.durationSec)} must be a number of seconds between 0.5 and 120.`);
    let render: ShotRender | undefined;
    if (s.render !== undefined) {
      render = str(s.render) as ShotRender;
      if (!SHOT_RENDERS.includes(render)) { err(`${path}.render`, `Render ${JSON.stringify(s.render)} must be one of: ${SHOT_RENDERS.join(", ")}.`); render = undefined; }
    }
    const mode = render ?? "ai";
    const prompt = str(s.prompt) ?? "";
    if (!prompt && mode === "ai") err(`${path}.prompt`, `Shot "${id}" needs a clip generation "prompt".`);
    const used = strList(s.assets, `${path}.assets`);
    used.forEach((a, j) => { if (!assetIds.has(a)) err(`${path}.assets[${j}]`, unknownAsset(a)); });
    const references = referencesOf(s.references, `${path}.references`, used);
    const shot: StoryShot = { id, title: str(s.title) || id, description: str(s.description) ?? "", durationSec: dur, prompt, assets: used, qa: strList(s.qa, `${path}.qa`) };
    if (references) shot.references = references;
    if (s.genDurationSec !== undefined) {
      const g = num(s.genDurationSec);
      if (g === undefined || g < 0.5 || g > 120) warn(`${path}.genDurationSec`, `genDurationSec ${JSON.stringify(s.genDurationSec)} is ignored: use seconds between 0.5 and 120.`);
      else if (Number.isFinite(dur) && g < dur - 1e-9) warn(`${path}.genDurationSec`, `genDurationSec ${fmt(g)} is shorter than durationSec ${fmt(dur)}; it is ignored. Generate at least the shot length.`);
      else if (!Number.isFinite(dur) || Math.abs(g - dur) > 1e-9) shot.genDurationSec = g;
    }
    const camera = str(s.camera), dialogue = str(s.dialogue);
    if (camera) shot.camera = camera;
    if (dialogue) shot.dialogue = dialogue;
    if (render) shot.render = render;
    const clip = s.clip === undefined ? undefined : str(s.clip) ?? "";
    if (mode === "ai") {
      if (clip !== undefined) warn(`${path}.clip`, `"clip" only applies to render "html" or "still"; it is ignored for this AI-generated shot.`);
    } else if (!clip) err(`${path}.clip`, `A render "${mode}" shot needs "clip": the id of ${mode === "html" ? "an html" : "an image"} asset.`);
    else {
      const a = assetById.get(clip);
      if (!a) err(`${path}.clip`, unknownAsset(clip));
      else if (mode === "html" ? a.type !== "html" : a.type !== "image") err(`${path}.clip`, `Render "${mode}" needs ${mode === "html" ? "an html" : "an image"} asset, but "${clip}" is type ${a.type}.`);
    }
    if (clip) shot.clip = clip;
    if (s.params !== undefined) {
      if (mode !== "html") warn(`${path}.params`, `"params" only applies to render "html" shots (values for the clip's params); it is ignored here.`);
      else { const ps = htmlParamsOf(s.params, `${path}.params`, clip && assetById.get(clip)?.type === "html" ? clip : undefined); if (ps) shot.params = ps; }
    }
    const layers = layersOf(s.layers, `${path}.layers`, dur);
    if (layers) shot.layers = layers;
    if (s.captions !== undefined) {
      if (typeof s.captions !== "boolean") warn(`${path}.captions`, "captions should be true or false; ignoring it.");
      else { shot.captions = s.captions; if (s.captions && !dialogue) warn(`${path}.captions`, `captions is on but shot "${id}" has no "dialogue"; nothing will be captioned.`); }
    }
    const effects = effectsOf(s.effects, `${path}.effects`, dur);
    if (effects) shot.effects = effects;
    // V2-SB-126: a layer that follows the shot needs an effect that moves or zooms the picture while it is on screen.
    layers?.forEach((l, j) => {
      if (l.follow !== "shot") return;
      const moving = (effects ?? []).some((e) => (e.startSec ?? 0) < l.endSec && (e.endSec ?? dur) > l.startSec && effectMoves(e.preset, e.params));
      if (!moving) warn(`${path}.layers[${j}].follow`, `Layer "${l.id}" follows the shot, but no effect moves or zooms shot "${id}" while it is on screen, so it stays put.`);
    });
    const keyframe = keyframeOf(s.keyframe, `${path}.keyframe`, id, mode);
    if (keyframe) {
      shot.keyframe = keyframe;
      // The keyframe is the start frame: another start frame stated for the clip is used as details only.
      shot.references?.forEach((r, j) => { if (r.role === "start-frame") { warn(`${path}.references[${j}].role`, `Shot "${id}" has a keyframe, which is its start frame; "${r.asset}" is used as "detail".`); r.role = "detail"; } });
    }
    shots.push(shot);
  }

  // Frame dependencies: shot B using "last frame of A" depends on A's clip.
  const order = new Map(shots.map((s, i) => [s.id, i]));
  const deps = new Map(shots.map((s) => [s.id, [...s.assets, ...(s.keyframe?.references.map(assetRefId) ?? [])].flatMap((a) => { const src = assetById.get(a)?.source; return src?.type === "lastFrame" ? [src.shot] : []; })]));
  shots.forEach((s, i) => (deps.get(s.id) ?? []).forEach((d) => {
    if (d === s.id) err(`shots[${i}].assets`, `Shot "${s.id}" can't use its own last frame.`);
    else if ((order.get(d) ?? -1) > i) warn(`shots[${i}].assets`, `Shot "${s.id}" uses the last frame of "${d}", which comes later in the order.`);
  }));
  const depCycle = findCycle(new Map([...deps].map(([k, v]) => [k, v.filter((d) => d !== k)])));
  if (depCycle) err("shots", `Last-frame links form a loop: ${depCycle.join(" → ")}.`);
  // V2-SB-125: audio cues (voiceover, music beds, sound effects) placed by shot.
  const audio: StoryAudio[] = [];
  if (raw.audio !== undefined && !Array.isArray(raw.audio)) err("audio", '"audio" must be a list of cues.');
  else (raw.audio as unknown[] | undefined)?.forEach((c, i) => {
    const path = `audio[${i}]`;
    if (!isObj(c)) return err(path, `Each audio cue must be an object { "asset", "kind", "from", … }.`);
    const id = str(c.id) || `audio${i + 1}`;
    if (audio.some((x) => x.id === id)) err(`${path}.id`, `Audio cue id "${id}" is used twice.`);
    const asset = str(c.asset) ?? "";
    const a = assetById.get(asset);
    if (!a) err(`${path}.asset`, asset ? `Unknown asset "${asset}". Declare it in "assets" with "type": "audio".` : `Each audio cue needs "asset": the id of an audio asset.`);
    else if (a.type !== "audio") err(`${path}.asset`, `Asset "${asset}" is a ${a.type}; an audio cue needs an asset with "type": "audio".`);
    const kind = str(c.kind) as AudioKind | undefined;
    if (!kind || !AUDIO_KINDS.includes(kind)) err(`${path}.kind`, `Kind ${JSON.stringify(c.kind ?? null)} must be one of: ${AUDIO_KINDS.join(", ")}.`);
    const from = str(c.from) ?? "";
    if (!shotIds.has(from)) err(`${path}.from`, from ? `Unknown shot "${from}".` : `Each audio cue needs "from": the shot it starts in.`);
    let to = str(c.to);
    if (c.to !== undefined && !to) { warn(`${path}.to`, `"to" must be a shot id; it is ignored.`); to = undefined; }
    if (to && !shotIds.has(to)) err(`${path}.to`, `Unknown shot "${to}".`);
    else if (to && shotIds.has(from) && (order.get(to) ?? 0) < (order.get(from) ?? 0)) err(`${path}.to`, `Shot "${to}" comes before "${from}"; "to" is the last shot the cue plays under.`);
    const cue: StoryAudio = { id, asset, kind: kind ?? "sfx", from, ...(to && to !== from ? { to } : {}) };
    const sec = (k: "atSec" | "durationSec" | "fadeInSec" | "fadeOutSec", min: number, rule: string) => {
      if (c[k] === undefined) return;
      const n = num(c[k]);
      if (n === undefined || n < min) warn(`${path}.${k}`, `${k} ${JSON.stringify(c[k])} is ignored: ${rule}.`);
      else cue[k] = n;
    };
    sec("atSec", 0, "use seconds from the start of the \"from\" shot, 0 or more");
    sec("durationSec", 0.001, "use seconds greater than 0");
    sec("fadeInSec", 0, "use seconds, 0 or more");
    sec("fadeOutSec", 0, "use seconds, 0 or more");
    if (c.volume !== undefined) {
      const v = num(c.volume);
      if (v === undefined || v < 0 || v > 1) warn(`${path}.volume`, `Volume ${JSON.stringify(c.volume)} is ignored: use 0 to 1 (default ${AUDIO_DEFAULTS[cue.kind].volume}).`);
      else cue.volume = v;
    }
    const fromShot = shots.find((s) => s.id === from);
    if (fromShot && cue.atSec !== undefined && cue.atSec >= fromShot.durationSec) warn(`${path}.atSec`, `atSec ${cue.atSec} is at or past the end of shot "${from}" (${fromShot.durationSec} s); the cue starts later than that shot.`);
    if (cue.to && cue.durationSec !== undefined) warn(`${path}.durationSec`, `The cue has both "to" and "durationSec"; it stops at whichever comes first.`);
    audio.push(cue);
  });

  const usedBy = (id: string) => audio.some((c) => c.asset === id) || shots.some((s) => s.assets.includes(id) || s.keyframe?.references.some((r) => assetRefId(r) === id) || (s.render && s.render !== "ai" && s.clip === id) || s.layers?.some((l) => l.type !== "text" && l.asset === id));
  assets.forEach((a, i) => { if (!usedBy(a.id) && !assets.some((b) => b.references.some((r) => assetRefId(r) === a.id))) warn(`assets[${i}]`, `Asset "${a.id}" isn't used by any shot.`); });

  let connections: StoryConnection[] = [];
  if (raw.connections === undefined) {
    connections = shots.slice(1).map((s, i) => ({ from: shots[i].id, to: s.id, kind: (deps.get(s.id) ?? []).includes(shots[i].id) ? "continuity" : "cut" }));
  } else if (!Array.isArray(raw.connections)) err("connections", '"connections" must be a list.');
  else raw.connections.forEach((c, i) => {
    const path = `connections[${i}]`;
    if (!isObj(c)) return err(path, "Each connection must be an object.");
    const from = str(c.from) ?? "", to = str(c.to) ?? "";
    if (!shotIds.has(from)) err(`${path}.from`, `Unknown shot "${from}".`);
    if (!shotIds.has(to)) err(`${path}.to`, `Unknown shot "${to}".`);
    const kind = (str(c.kind) ?? "cut") as ConnectionKind;
    if (!CONNECTION_KINDS.includes(kind)) err(`${path}.kind`, `Kind "${kind}" must be one of: ${CONNECTION_KINDS.join(", ")}.`);
    const note = str(c.note);
    let transition: StoryTransition | undefined;
    if (c.transition !== undefined) {
      const t = c.transition;
      if (!isObj(t) || !str(t.preset)) warn(`${path}.transition`, `Should be { "preset": "<transition id>", "params"?: { "durationSec"?: number } }; using a cut. Transitions: ${list(listPresets("transition").map((d) => d.id))}.`);
      else {
        const preset = presetRef("transition", t.preset, `${path}.transition.preset`, "a cut")!;
        const params = paramsOf(t.params, `${path}.transition.params`, descriptorOf("transition", preset), ["durationSec"]);
        if (params && params.durationSec !== undefined && !(typeof params.durationSec === "number" && params.durationSec > 0)) {
          warn(`${path}.transition.params.durationSec`, `durationSec ${JSON.stringify(params.durationSec)} is ignored; using ${DEFAULT_TRANSITION_SEC} s.`);
          delete params.durationSec;
        }
        transition = { preset, ...(params ? { params } : {}) };
        const fi = order.get(from), ti = order.get(to);
        if (fi !== undefined && ti !== undefined && ti !== fi + 1) warn(`${path}.transition`, `"${from}" and "${to}" are not next to each other, so this transition is played as a cut (it is kept for export).`);
      }
    }
    connections.push({ from, to, kind, ...(note ? { note } : {}), ...(transition ? { transition } : {}) });
  });

  if (errors.length) return { ok: false, errors, warnings };
  return { ok: true, doc: { format: STORYBOARD_FORMAT, meta, assets, shots, connections, ...(audio.length ? { audio } : {}) }, warnings };
}

/**
 * The role an image plays when a shot does not say (V2-SB-120): a frame or last frame opens the clip, a character
 * gives identity, a style the look, anything else (location, prop, image …) details only.
 */
export function inferReferenceRole(type: StoryAssetType, lastFrame = false): ReferenceRole {
  if (lastFrame || type === "frame") return "start-frame";
  if (type === "character") return "identity";
  if (type === "style") return "look";
  return "detail";
}

/** First cycle in a dependency map (node → nodes it depends on), as a path ending where it started. */
export function findCycle(graph: Map<string, string[]>): string[] | undefined {
  const state = new Map<string, 1 | 2>();
  const stack: string[] = [];
  const visit = (n: string): string[] | undefined => {
    if (state.get(n) === 2) return undefined;
    if (state.get(n) === 1) return [...stack.slice(stack.indexOf(n)), n];
    state.set(n, 1); stack.push(n);
    for (const d of graph.get(n) ?? []) { if (!graph.has(d)) continue; const c = visit(d); if (c) return c; }
    stack.pop(); state.set(n, 2);
    return undefined;
  };
  for (const n of graph.keys()) { const c = visit(n); if (c) return c; }
  return undefined;
}

/** A StoryDoc as storyboard JSON text in the documented form (sources as authoredSource writes them). */
export function storyDocJson(doc: StoryDoc): string {
  return JSON.stringify({ ...doc, assets: doc.assets.map((a) => ({ ...a, source: authoredSource(a.source) })) }, null, 2);
}

/** One-line summary for the import preview. */
export function storySummary(doc: StoryDoc): string {
  const total = doc.shots.reduce((t, s) => t + s.durationSec, 0);
  const frames = doc.assets.filter((a) => a.source.type === "lastFrame").length;
  const qa = doc.assets.reduce((t, a) => t + a.qa.length, 0) + doc.shots.reduce((t, s) => t + s.qa.length, 0);
  const n = (k: number, one: string, many = `${one}s`) => `${k} ${k === 1 ? one : many}`;
  const layers = doc.shots.reduce((t, s) => t + (s.layers?.length ?? 0), 0);
  const effects = doc.shots.reduce((t, s) => t + (s.effects?.length ?? 0), 0);
  const transitions = doc.connections.filter((c) => c.transition).length;
  const cues = doc.audio?.length ?? 0;
  const extra = [layers && n(layers, "layer"), effects && n(effects, "effect"), transitions && n(transitions, "transition"), cues && n(cues, "audio cue")].filter(Boolean);
  return `${n(doc.shots.length, "shot")} · ${Math.round(total * 10) / 10}s · ${n(doc.assets.length, "asset")}${frames ? ` (${n(frames, "last-frame link")})` : ""} · ${n(qa, "QA check")}${extra.length ? ` · ${extra.join(" · ")}` : ""}`;
}

/**
 * Character ranges of every member in a JSON text, keyed by the validator's paths
 * ("meta.title", "shots[0].durationSec"). A member's range covers `"key": value`; array items cover the value.
 * Best effort: stops quietly at the first syntax error.
 */
export function jsonPathRanges(json: string): Map<string, { start: number; end: number }> {
  const out = new Map<string, { start: number; end: number }>();
  let i = 0;
  const ws = () => { while (i < json.length && /\s/.test(json[i])) i++; };
  const str = () => { const a = i++; while (i < json.length && json[i] !== '"') i += json[i] === "\\" ? 2 : 1; i++; return json.slice(a, i); };
  const value = (path: string, start: number): void => {
    ws();
    const c = json[i];
    if (c === "{") {
      i++; ws();
      while (i < json.length && json[i] !== "}") {
        ws(); const ks = i; if (json[i] !== '"') throw 0;
        const key = JSON.parse(str()) as string; ws(); if (json[i++] !== ":") throw 0;
        value(path ? `${path}.${key}` : key, ks); ws();
        if (json[i] === ",") i++;
        else if (json[i] !== "}") throw 0;
      }
      i++;
    } else if (c === "[") {
      i++; ws(); let n = 0;
      while (i < json.length && json[i] !== "]") {
        ws(); value(`${path}[${n++}]`, i); ws();
        if (json[i] === ",") i++;
        else if (json[i] !== "]") throw 0;
      }
      i++;
    } else if (c === '"') str();
    else { const m = /^[^,}\]\s]+/.exec(json.slice(i)); if (!m) throw 0; i += m[0].length; }
    if (path) out.set(path, { start, end: i });
  };
  try { value("", 0); } catch { /* partial map is still useful */ }
  return out;
}

/** Where an issue points in the pasted text (which may wrap the JSON in chat text or a fence); falls back to the nearest parent. */
export function locateIssue(text: string, issue: StoryIssue): { start: number; end: number } | undefined {
  const json = extractJson(text);
  const base = Math.max(0, text.indexOf(json));
  if (issue.at !== undefined) { const end = json.indexOf("\n", issue.at); return { start: base + issue.at, end: base + (end < 0 ? json.length : end) }; }
  if (!issue.path) return undefined;
  const ranges = jsonPathRanges(json);
  for (let p = issue.path; p; p = p.replace(/(\.[^.[\]]+|\[\d+\])$/, "") ) {
    const r = ranges.get(p);
    if (r) return { start: base + r.start, end: base + r.end };
    if (!/(\.[^.[\]]+|\[\d+\])$/.test(p)) break;
  }
  return undefined;
}
